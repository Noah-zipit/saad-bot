#!/usr/bin/env python3
"""Generate src/lib/cards.ts from REAL Shoob cards.

Sources (CardKami repo, ~/workspace/jojo-stand-generator/):
  - shoob.js  : roster id -> {img (cdn.shoob.gg), page (shoob.gg/cards/info/..)}
                generated 2026-10-17 via shoob.gg cardindex search API.
  - stands.js : LEGENDS roster: id, name, series, stats {pow,spd,rng,dur,pre,pot}
                grades E..SSS (E=1 .. SSS=8; "∞" and "—" count as SSS).

Power = sum of the six stat grades (range 6-48).
Rarity by power rank (matches the bot's pack odds 70/20/8/2):
  top 3 -> Legendary, next 11 -> Epic, next 28 -> Rare, rest Common.
Output: src/lib/cards.ts (overwrites the invented 36-card pool).
"""
import re, sys

GRADE = {'E': 1, 'D': 2, 'C': 3, 'B': 4, 'A': 5, 'S': 6, 'SS': 7, 'SSS': 8, '∞': 8, '—': 8, '?': 3}  # '?' = unknown stat (only King Crimson pot) -> average 3
SHOOB = '/home/hatch/workspace/jojo-stand-generator/shoob.js'
LEGENDS = '/home/hatch/workspace/jojo-stand-generator/stands.js'
OUT = '/home/hatch/workspace/saad-bot/src/lib/cards.ts'

shoob = {}
for m in re.finditer(r'"([a-z0-9-]+)": \{ img: "([^"]+)", page: "([^"]+)" \}', open(SHOOB).read()):
    shoob[m.group(1)] = (m.group(2), m.group(3))

legends_src = open(LEGENDS).read()
cards = []
unusual = set()
for m in re.finditer(
    r'id: "([a-z0-9-]+)",\s*name: "([^"]+)",[^}]*?series: "([^"]+)",.*?stats: \{ pow: "([^"]+)", spd: "([^"]+)", rng: "([^"]+)", dur: "([^"]+)", pre: "([^"]+)", pot: "([^"]+)" \}',
    legends_src, re.S):
    cid, name, series, grades = m.group(1), m.group(2), m.group(3), m.groups()[3:]
    if cid not in shoob:
        continue
    for g in grades:
        if g not in GRADE:
            unusual.add(g)
    power = sum(GRADE[g] for g in grades)
    img, page = shoob[cid]
    cards.append({'id': cid, 'name': name, 'series': series, 'img': img, 'page': page, 'power': power})

print(f"joined: {len(cards)} cards (shoob keys: {len(shoob)})", file=sys.stderr)
if unusual:
    print(f"UNUSUAL GRADES: {sorted(unusual)}", file=sys.stderr)
    sys.exit(1)
if len(cards) != len(shoob):
    print("MISMATCH: some shoob keys have no LEGENDS entry", file=sys.stderr)
    sys.exit(1)

cards.sort(key=lambda c: (-c['power'], c['name']))
for i, c in enumerate(cards):
    c['rarity'] = 'Legendary' if i < 3 else 'Epic' if i < 14 else 'Rare' if i < 42 else 'Common'

from collections import Counter
print("rarity counts:", dict(Counter(c['rarity'] for c in cards)), file=sys.stderr)
print("power range:", cards[-1]['power'], "->", cards[0]['power'], file=sys.stderr)
print("top 5:", [(c['name'], c['power'], c['rarity']) for c in cards[:5]], file=sys.stderr)
print("bottom 3:", [(c['name'], c['power']) for c in cards[-3:]], file=sys.stderr)

def ts_str(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"

lines = []
lines.append("// Card pool for the !cards game — REAL Shoob cards (shoob.gg).")
lines.append("// Generated by scripts/gen-shoob-cards.py from CardKami's data:")
lines.append("//   shoob.js  — 139 real Shoob cards: cdn.shoob.gg image + shoob.gg page each")
lines.append("//   stands.js — LEGENDS roster: name, series, stats (grades E..SSS = 1..8)")
lines.append("// Power = sum of the six stat grades (6-48). Rarity by power rank:")
lines.append("//   top 3 Legendary, next 11 Epic, next 28 Rare, rest Common.")
lines.append("// Pack odds stay 70/20/8/2 Common/Rare/Epic/Legendary per slot.")
lines.append("// No invented cards: the old 36-card original pool is gone for good.")
lines.append("")
lines.append("export type Rarity = 'Common' | 'Rare' | 'Epic' | 'Legendary'")
lines.append("")
lines.append("export interface CardDef {")
lines.append("  id: string")
lines.append("  name: string")
lines.append("  series: string")
lines.append("  img: string   // cdn.shoob.gg card art")
lines.append("  page: string  // shoob.gg card page (credit)")
lines.append("  rarity: Rarity")
lines.append("  power: number")
lines.append("}")
lines.append("")
lines.append("export const RARITY_EMOJI: Record<Rarity, string> = {")
lines.append("  Common: '⚪',")
lines.append("  Rare: '🔵',")
lines.append("  Epic: '🟣',")
lines.append("  Legendary: '🟡'")
lines.append("}")
lines.append("")
lines.append("export const CARDS: CardDef[] = [")
for c in cards:
    lines.append(f"  {{ id: {ts_str(c['id'])}, name: {ts_str(c['name'])}, series: {ts_str(c['series'])}, img: {ts_str(c['img'])}, page: {ts_str(c['page'])}, rarity: {ts_str(c['rarity'])}, power: {c['power']} }},")
lines.append("]")
lines.append("")
lines.append("export const CARD_BY_ID: Record<string, CardDef> = Object.fromEntries(")
lines.append("  CARDS.map(c => [c.id, c])")
lines.append(")")
lines.append("")
lines.append("/** Find a card by id or by (partial, case-insensitive) name. */")
lines.append("export function findCard(query: string): CardDef | undefined {")
lines.append("  const q = query.trim().toLowerCase()")
lines.append("  if (!q) return undefined")
lines.append("  return CARD_BY_ID[q] ?? CARDS.find(c => c.name.toLowerCase() === q) ?? CARDS.find(c => c.name.toLowerCase().includes(q))")
lines.append("}")
lines.append("")
lines.append("function rollOne(): CardDef {")
lines.append("  const r = Math.random()")
lines.append("  const rarity: Rarity = r < 0.02 ? 'Legendary' : r < 0.10 ? 'Epic' : r < 0.30 ? 'Rare' : 'Common'")
lines.append("  const pool = CARDS.filter(c => c.rarity === rarity)")
lines.append("  return pool[Math.floor(Math.random() * pool.length)]")
lines.append("}")
lines.append("")
lines.append("/** A pack is 3 cards, rolled independently by rarity odds. */")
lines.append("export function rollPack(): CardDef[] {")
lines.append("  return [rollOne(), rollOne(), rollOne()]")
lines.append("}")
lines.append("")
lines.append("export function formatCard(c: CardDef, count?: number): string {")
lines.append("  const dup = count && count > 1 ? ` ×${count}` : ''")
lines.append("  return `${RARITY_EMOJI[c.rarity]} *${c.name}* — ${c.rarity}, ⚔️ ${c.power}${dup}\\n_${c.series}_`")
lines.append("}")
lines.append("")

open(OUT, 'w').write('\n'.join(lines))
print(f"wrote {OUT}", file=sys.stderr)
